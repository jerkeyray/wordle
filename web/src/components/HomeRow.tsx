"use client";

import { useSyncExternalStore } from "react";
import WORDS from "@/lib/home-words.json";

/**
 * One row, spelled out.
 *
 * Three rows of near-invisible tiles were decoration pretending to be a board.
 * A single row in a solid fill, set in the same serif as the wordmark, is the
 * signature instead: one confident shape rather than eighteen that whisper.
 *
 * The fill is the colour that already means "right letter, right place", so a
 * whole row of it says "solved" in the game's own grammar rather than inventing
 * a decorative colour that means nothing.
 */
// A tiny invitation to the kind of word the game is for, rather than generic
// interface copy such as “learn” or “begin”. WORDS is the bank's five-letter
// "stretch" answers (generated by `pnpm readme:sync`), so it is always a word
// the game can actually deal.

/**
 * A fresh word on every visit, picked once per page load and then held, so
 * re-renders never reshuffle it under the player. Read as an external store
 * rather than computed in render: a random pick on the server would never
 * match the browser's, and a hydration mismatch is not worth a flourish. The
 * server sees nothing, so the empty row filling in on the client is the load
 * animation.
 */
let picked: string | null = null;
const neverChanges = () => () => {};
const wordForThisVisit = () => (picked ??= WORDS[Math.floor(Math.random() * WORDS.length)]);
const noWordOnServer = () => null;

export function HomeRow() {
  const word = useSyncExternalStore(neverChanges, wordForThisVisit, noWordOnServer);

  return (
    <div className="home-row" aria-hidden>
      {Array.from({ length: 5 }, (_, i) => (
        <span
          key={i}
          className="home-tile"
          data-filled={word ? true : undefined}
          style={{ animationDelay: `${i * 55}ms` }}
        >
          {word?.[i] ?? ""}
        </span>
      ))}
    </div>
  );
}
